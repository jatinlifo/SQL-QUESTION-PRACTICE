(SELECT u.name AS results
FROM  Users AS u
INNER JOIN MovieRating As m 
ON u.user_id = m.user_id
GROUP BY u.user_id, u.name
ORDER BY COUNT(m.rating) DESC, u.name
LIMIT 1)

UNION ALL

(SELECT Movies.title AS results
FROM Movies 
INNER JOIN MovieRating AS m
ON Movies.movie_id = m.movie_id
WHERE m.created_at >= '2020-02-01'AND m.created_at < '2020-03-01'
GROUP BY Movies.movie_id, Movies.title
ORDER BY AVG(m.rating) DESC, title
LIMIT 1);
